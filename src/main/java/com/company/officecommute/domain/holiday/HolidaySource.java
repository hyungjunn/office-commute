package com.company.officecommute.domain.holiday;

/**
 * 공휴일 원장 행의 출처. 같은 날짜에 출처별로 한 행씩 공존할 수 있다.
 * <p>
 * API 행은 재동기화가 통째로 갈아끼우는 대상이고, MANUAL·COMPANY 행은 사람이 입력한 값이므로
 * 동기화가 지우지 않는다. 이 구분이 없으면 수동 보정이 다음 동기화에 조용히 사라진다.
 * <p>
 * 예외가 하나 있다: API가 같은 날짜를 공휴일로 주면 (MANUAL, is_holiday=true) 행은 삭제된다.
 * 그 행의 존재 이유가 "API가 아직 안 준 날을 대신 채운다"이므로, API 행이 생긴 순간 소임이 끝난다.
 * 부정 오버라이드(MANUAL, is_holiday=false)는 정반대 의도이므로 그대로 남는다.
 */
public enum HolidaySource {

    /**
     * 공공데이터포털 동기화가 적재한 법정 공휴일. 연 단위 재동기화가 삭제 후 재삽입한다.
     */
    API,

    /**
     * 관리자 보정. 사후 지정(예: 임시공휴일)을 미리 넣거나, API가 잘못 준 날을
     * is_holiday=false로 근무일로 되돌릴 때 쓴다. 부정 오버라이드가 가능한 유일한 출처다.
     */
    MANUAL,

    /**
     * 회사 지정 휴일(창립기념일 등). 법정 공휴일이 아니므로 API가 절대 주지 않고,
     * 항상 is_holiday=true다 — 회사가 "이 날은 근무일"이라고 선언하는 건 휴일 지정이 아니라
     * 아무것도 하지 않는 것과 같기 때문이다.
     */
    COMPANY
}
